// Scans public/assets/gallery/{aesthetic,before-after}/<category>/ for before-after
// photos and writes src/data/plasticGalleryManifest.ts — a plain map of
// "<top>/<category>" -> [image URL, ...], smallest files first so the Premium
// Proposal PDF picks the fastest-loading shots.
//
// Run after adding or changing photos:  npm run gallery
//
// Safe to run with the folders missing: it just writes an empty manifest.

import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GALLERY_DIR = join(ROOT, 'public', 'assets', 'gallery');
const OUT_FILE = join(ROOT, 'src', 'data', 'plasticGalleryManifest.ts');
const TOP_LEVEL = ['aesthetic', 'before-after'];
const IMAGE_RE = /\.(jpe?g|png|webp)$/i;
// Working files / layered exports that are not clean before-after shots.
const SKIP_RE = /(-recovered|copy-recovered|final frame)/i;

/** @param {string} dir */
function imageFilesSortedBySize(dir) {
  return readdirSync(dir)
    .filter((name) => IMAGE_RE.test(name) && !SKIP_RE.test(name))
    .map((name) => {
      const full = join(dir, name);
      return { name, size: statSync(full).size };
    })
    .sort((a, b) => a.size - b.size)
    .map((entry) => entry.name);
}

/** @param {string} relPath */
function toUrl(relPath) {
  return '/assets/gallery/' + relPath.split(/[\\/]/).map(encodeURIComponent).join('/');
}

/** @type {Record<string, string[]>} */
const manifest = {};

for (const top of TOP_LEVEL) {
  const topDir = join(GALLERY_DIR, top);
  if (!existsSync(topDir)) continue;

  for (const category of readdirSync(topDir)) {
    const categoryDir = join(topDir, category);
    if (!statSync(categoryDir).isDirectory()) continue;

    const files = imageFilesSortedBySize(categoryDir);
    if (!files.length) continue;

    const key = `${top}/${category}`;
    manifest[key] = files.map((name) => toUrl(relative(GALLERY_DIR, join(categoryDir, name))));
  }
}

const keys = Object.keys(manifest).sort();
const total = keys.reduce((sum, key) => sum + manifest[key].length, 0);

const body = keys
  .map((key) => {
    const urls = manifest[key].map((url) => `    ${JSON.stringify(url)},`).join('\n');
    return `  ${JSON.stringify(key)}: [\n${urls}\n  ],`;
  })
  .join('\n');

const literal = keys.length ? `{\n${body}\n}` : '{}';

const file = `// AUTO-GENERATED by scripts/build-gallery-manifest.mjs — do not edit by hand.
// Run \`npm run gallery\` after adding or changing photos under
// public/assets/gallery/. ${keys.length} folders, ${total} images.

/** "<top>/<category>" -> before-after image URLs, smallest file first. */
export const GALLERY_MANIFEST: Record<string, string[]> = ${literal};
`;

if (!existsSync(dirname(OUT_FILE))) mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, file);

console.log(`gallery manifest: ${keys.length} folders, ${total} images -> ${relative(ROOT, OUT_FILE)}`);
